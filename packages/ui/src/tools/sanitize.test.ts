// @vitest-environment jsdom

import { describe, expect, it } from 'vitest';

import { sanitizeHtml } from './sanitize';

describe('sanitizeHtml', () => {
  it('preserves the structural markup and styles generated by Shiki', () => {
    const highlightedCode = [
      '<pre class="shiki github-light-default" style="background-color:#fff;color:#24292f" tabindex="0">',
      '<code><span class="line" style="color:#cf222e;font-style:italic">const value = 1;</span></code>',
      '</pre>'
    ].join('');

    const sanitizedCode = sanitizeHtml(highlightedCode);
    const container = document.createElement('div');
    container.innerHTML = sanitizedCode;

    const pre = container.querySelector('pre');
    const line = container.querySelector('span.line');
    expect(pre?.classList.contains('shiki')).toBe(true);
    expect(pre?.getAttribute('style')).toContain('background-color');
    expect(pre?.getAttribute('tabindex')).toBe('0');
    expect(line?.textContent).toBe('const value = 1;');
    expect(line?.getAttribute('style')).toContain('font-style');
  });

  it('removes executable markup and attributes', () => {
    const unsafeCode = [
      '<pre class="shiki"><code>',
      '<span class="line" onclick="alert(1)">safe source</span>',
      '<script>alert(2)</script>',
      '<a href="javascript:alert(3)">unsafe link</a>',
      '</code></pre>'
    ].join('');

    const sanitizedCode = sanitizeHtml(unsafeCode);

    expect(sanitizedCode).toContain('safe source');
    expect(sanitizedCode).not.toMatch(/<script/i);
    expect(sanitizedCode).not.toMatch(/onclick/i);
    expect(sanitizedCode).not.toMatch(/javascript:/i);
  });
});
