import { error } from '@sveltejs/kit';

import { classroomhub, getApiHeaders } from '$lib/utils/services/api';
import { safeServerApi } from '$lib/utils/services/api/server';

/**
 * What the sheet says when the server could not be asked.
 *
 * Only reachable if the context request fails while the answers themselves loaded — rare,
 * and a sheet with English labels beats a sheet with none.
 */
const FALLBACK_LABELS = {
  title: 'Answer sheet',
  fullName: 'Candidate',
  className: 'Class',
  candidateNumber: 'Candidate no.',
  score: 'Score',
  correct: 'Correct',
  timeTaken: 'Time taken',
  startedAt: 'Started',
  submittedAt: 'Submitted',
  leaves: 'Times left',
  question: 'Q',
  chosen: 'Chosen by candidate',
  key: 'Correct answer',
  note: 'Comment',
  unnamed: 'Unnamed',
  generatedAt: 'Generated',
  generatedBy: 'Generated by',
  minutes: 'min'
};

/**
 * The answer sheets, laid out for a printer.
 *
 * A teacher going through a paper in the room hands each candidate their own sheet: what
 * they chose, what the key says, and where the two differ. The workbook already carries all
 * of that, but a spreadsheet is not something anybody hands to a sixteen-year-old.
 *
 * There is no PDF writer behind this. The browser already has one — every print dialog can
 * save to PDF — and it renders Vietnamese correctly without an embedded font, which a
 * server-side writer would have had to carry and be checked glyph by glyph. What the page
 * owes in return is print CSS honest enough that the dialog's preview is the finished sheet.
 */
/**
 * The moment the sheet was printed, in ISO 8601 order.
 *
 * Same shape as the workbook's stamps and the sheet's own clocks: year first, and a space
 * between the date and the time rather than the two run together. A sheet found in a filing
 * cabinet next term must not have to work out which September it came from.
 */
function printedNow(now = new Date()): string {
  const parts = new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Asia/Ho_Chi_Minh',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    hour12: false
  }).formatToParts(now);

  const at = (type: string) => parts.find((part) => part.type === type)?.value ?? '';

  return `${at('year')}-${at('month')}-${at('day')} ${at('hour')}:${at('minute')}`;
}

export const load = async ({ params, url, cookies, locals }) => {
  const headers = getApiHeaders(cookies, '');

  /**
   * The selection travels as attempt ids, which are opaque.
   *
   * The workbook sends its selection in a body precisely so candidate names stay out of the
   * URL; a page cannot do that, so it sends the one identifier that names nobody. Empty
   * means every finished sitting, which is what a teacher printing for the whole class asks
   * for by not choosing anybody.
   */
  /**
   * The language of the sheet, which is not the language of this screen.
   *
   * It arrives on the URL because the print page opens in its own tab: a choice remembered
   * in the opener's `localStorage` is not visible here. Where nothing was chosen the
   * teacher's own locale is the best guess available, and the server resolves anything it
   * does not recognise to English.
   */
  const locale = url.searchParams.get('lang') || cookies.get('classroomhub_locale') || 'en';

  const attemptIds = (url.searchParams.get('attempts') ?? '')
    .split(',')
    .map((id) => id.trim())
    .filter(Boolean);

  const [examResult, keysResult, matrixResult, contextResult] = await Promise.all([
    safeServerApi(() => classroomhub.exam[':examId'].$get({ param: { examId: params.examId } }, headers)),
    safeServerApi(() =>
      classroomhub.exam[':examId']['answer-keys'].$get({ param: { examId: params.examId } }, headers)
    ),
    safeServerApi(() =>
      classroomhub.exam[':examId']['answer-matrix'].$post(
        { param: { examId: params.examId }, json: { attemptIds } },
        headers
      )
    ),
    safeServerApi(() =>
      classroomhub.exam[':examId']['print-context'].$get(
        { param: { examId: params.examId }, query: { lang: locale } },
        headers
      )
    )
  ]);

  if (!examResult.ok) {
    throw error(404, 'Exam not found');
  }

  if (!matrixResult.ok) {
    throw error(409, 'No finished sittings to print');
  }

  const matrix = matrixResult.body.data;

  /**
   * The letters each question offered, so a sheet can print the options nobody chose.
   *
   * The matrix carries only what was chosen and what is correct; a question where the whole
   * class picked A would otherwise print a single letter and hide that there were four.
   */
  const offered = new Map<number, string[]>();

  if (keysResult.ok) {
    for (const question of keysResult.body.data.questions) {
      const labels = question.options.map((option) => option.label);

      if (labels.length > 0) offered.set(question.position, labels);
    }
  }

  const context = contextResult.ok ? contextResult.body.data : null;

  return {
    courseId: params.id,
    /**
     * The sheet's wording, from the server, in the language asked for.
     *
     * Never from this app's own translations: the file is the server's artefact and the
     * workbook is written from the same table, so the two cannot drift apart. A failed
     * context request leaves the sheet with the server's English, which is a readable sheet
     * rather than a sheet of empty labels.
     */
    labels: context?.labels ?? FALLBACK_LABELS,
    examTitle: examResult.body.data.title,
    /**
     * The masthead and foot, which is what lets the page answer for itself once it is off
     * the screen: who issued it, what it records, when it was true and who asked for it.
     *
     * Printed here rather than read off the clock in the browser, because the time a sheet
     * claims to have been taken is the server's, not whatever the printing laptop believes.
     */
    issuer: {
      organizationName: context?.organizationName ?? null,
      organizationLogo: context?.organizationLogo ?? null,
      courseTitle: context?.courseTitle ?? null,
      printedBy: locals.user?.name ?? locals.user?.email ?? null,
      printedAt: printedNow()
    },
    questions: matrix.questions.map((question) => ({
      position: question.position,
      key: question.key,
      // Whatever the paper offered, or failing that whatever anyone chose plus the key —
      // a sheet with one letter on it is still truthful, and better than no sheet.
      letters: offered.get(question.position) ?? []
    })),
    rows: matrix.rows
  };
};
