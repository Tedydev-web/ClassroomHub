import type { WorkbookLabels } from './exam-answer-workbook';

/**
 * The wording of the files this system produces, per language.
 *
 * Kept on the server rather than sent up with each request, because the file is the server's
 * artefact: a caller asks for a class's answers and says which language to write them in,
 * not what each column is called. A new language is a new entry here and nothing else.
 *
 * Two rules hold across every language, and both are about not translating what is not
 * words:
 *
 *  - **Dates and numbers do not move.** Every file stamps `2026-09-02 22:41` and writes a
 *    mark as `8.5`, in every language. A Vietnamese file that said `02/09/2026` would sort
 *    wrongly as a text column and read as February to an American; one that said `8,5`
 *    would be read as text by a spreadsheet whose own locale uses a point, and stop adding
 *    up.
 *  - **What a person typed is never translated.** The candidate's name, "12A", the paper's
 *    title and the school's name print as they were entered. Every export is therefore a
 *    mixed document, and the language only ever decides the labels around the data.
 */

export type ExportLocale = 'en' | 'vi';

/** The wording of the printed answer sheet, which needs a few things a workbook does not. */
export type SheetLabels = {
  title: string;
  fullName: string;
  className: string;
  candidateNumber: string;
  score: string;
  correct: string;
  timeTaken: string;
  startedAt: string;
  submittedAt: string;
  leaves: string;
  question: string;
  chosen: string;
  key: string;
  note: string;
  unnamed: string;
  generatedAt: string;
  generatedBy: string;
  minutes: string;
};

/**
 * The language to write a file in, from whatever the caller said.
 *
 * English when the caller said nothing or said something this does not have, because a file
 * in a language the reader does not speak is still a file, and one whose labels came back
 * `undefined` is a file with columns silently missing — the workbook drops any column it is
 * given no label for.
 */
export function resolveExportLocale(value: unknown): ExportLocale {
  return value === 'vi' ? 'vi' : 'en';
}

